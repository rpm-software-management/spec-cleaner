@pytest.mark.parametrize(
    'content',
    [
        # the phrase in a scriptlet comment talks about the script, not the file
        'Name: test\n\n%build\n# do not edit this auto generated spec file\nmake\n',
        # a comment after the first tag is outside the header comment block
        '#\nName: test\n# do not edit this auto generated spec file\n',
        # a different declaration in the header: the branding specs' template note
        '# Do not edit this auto generated file! Edit test.spec.in.\nName: test\n',
        # the myspell banner wording: measured in #485 to be treated gently by
        # the service run, so this declaration stays processed
        '## DO NOT EDIT THIS SPEC FILE\n## Generate: sh update.sh\nName: test\n',
        # the words of the phrase, in another order, are not the phrase
        '# this is part of the auto generated spec file, but opensuse\nName: test\n',
    ],
)
def test_autogenerated_lookalikes_are_processed(default_options, capsys, content):
    """Test that only the header warning skips; lookalikes are cleaned as usual."""
    options = default_options()
    spec = options['specfile']
    with open(spec, 'w', encoding='utf-8') as specfile:
        specfile.write(content)
    RpmSpecCleaner(options).run()
    assert capsys.readouterr().err == ''
    with open(options['output'], encoding='utf-8') as out:
        assert out.read() != content


@pytest.mark.parametrize(
    'line, expected',
    [
        ('%post -p /sbin/ldconfig', ('%post', '')),
        ('%postun -p /sbin/ldconfig -n libfoo1', ('%postun', '-n libfoo1')),
        ('%POST libs -p /sbin/ldconfig', ('%post', 'libs')),
        # plain macros in the name pair up fine
        ('%post -n %{name}%{sover} -p /sbin/ldconfig', ('%post', '-n %{name}%{sover}')),
        ('%post -n libfoo%{sover} -p /sbin/ldconfig', ('%post', '-n libfoo%{sover}')),
        # a conditional in the name does not survive the trip through
        # %ldconfig_scriptlets, so the pair is not merged
        ('%post -n libtorch%{?pkg_suffix} -p /sbin/ldconfig', None),
        ('%postun -n libfoo%{?bar:baz} -p /sbin/ldconfig', None),
        ('%post -n libfoo%{!?bar} -p /sbin/ldconfig', None),
        # the macro forwards no other option, and no second name
        ('%post -n libfoo1 -e -p /sbin/ldconfig', None),
        ('%post -n -p /sbin/ldconfig', None),
        ('%post libs extra -p /sbin/ldconfig', None),
        # a header continued inside a macro definition
        ('%post -p /sbin/ldconfig \\', None),
        ('%post -p /bin/bash', None),
        ('%post -n libfoo1', None),
        ('%pre -p /sbin/ldconfig', None),
        (' %post -p /sbin/ldconfig', None),
    ],
)
def test_ldconfig_half(line, expected):
    """Test which scriptlet headers count as half of an %ldconfig_scriptlets pair."""
    assert RpmSpecCleaner._ldconfig_half(line) == expected


@pytest.mark.parametrize(
    'lines, expected',
    [
        # the other branch of a conditional opened before the header is not its body
        (['%endif', '%files'], True),
        (['%else', '%if 0', 'echo', '%endif', 'echo', '%endif', '%files'], True),
        # both branches of a conditional opened after the header are
        (['%if 0', '%files', '%endif'], True),
        (['%if 0', '%else', 'echo', '%endif', '%files'], False),
        (['', '# comment', 'echo'], False),
        (['', '# comment'], True),
    ],
)
def test_is_lone_scriptlet(default_options, lines, expected):
    """Test that only a scriptlet without a body before the next section is lone."""
    cleaner = RpmSpecCleaner(default_options())
    assert cleaner._is_lone_scriptlet(['%post -p /sbin/ldconfig', *lines], 0) is expected
